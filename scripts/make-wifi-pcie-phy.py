"""Extract PCIe0 PHY register data from the already captured Ace 5 DT."""
import argparse
import hashlib
from pathlib import Path
import re
import struct

SOURCE_SHA256='a23d858906208fcd7f9567aa6d6d7847e9e03fd5da448dd8e3b9a298a81de0a1'
TABLE_SHA256='980eb829648394dc1b8969a0cdc436bba3be9717cb455b08fb6c08d5ae3592ff'

def generate(data):
    if hashlib.sha256(data).hexdigest()!=SOURCE_SHA256:
        raise ValueError('Unverified Ace 5 running-device.dts')
    text=data.decode()
    start=text.index('qcom,pcie@1c00000 {')
    match=re.search(r'qcom,phy-sequence = <([^>]+)>;',text[start:])
    if not match:raise ValueError('Missing PCIe0 PHY table')
    values=[int(v,0) for v in match[1].split()]
    packed=struct.pack('<'+'I'*len(values),*values)
    if len(values)!=345 or hashlib.sha256(packed).hexdigest()!=TABLE_SHA256:
        raise ValueError('Unexpected PCIe0 PHY sequence')
    lines=['/* Generated by scripts/make-wifi-pcie-phy.py from the captured Android DT.',
           ' * Register data SHA256: '+TABLE_SHA256, ' */',
           '#ifndef GIULIA_WIFI_PCIE_PHY_H', '#define GIULIA_WIFI_PCIE_PHY_H',
           'static const struct gw_phy_word gw_phy_sequence[] = {']
    for offset,value,delay in zip(values[::3],values[1::3],values[2::3]):
        if offset&3 or offset>0x1ffc or value>255 or delay>1000:
            raise ValueError('PHY register data out of bounds')
        lines.append(f'  {{0x{offset:04x},0x{value:02x},{delay}}},')
    return '\n'.join([*lines,'};','#endif',''])

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--dts',type=Path,required=True)
    p.add_argument('--out',type=Path,required=True)
    a=p.parse_args()
    data=generate(a.dts.read_bytes())
    with a.out.open('x',newline='\n') as f:f.write(data)
    print('Verified 115 board-specific PCIe0 PHY register entries')
