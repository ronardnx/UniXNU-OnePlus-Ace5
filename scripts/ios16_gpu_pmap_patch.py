"""Generate the native GPU pmap gate for the fixed hardware-fence carveout.

The injected blocks are the only native page-table code of this layer: two
includes at the top of the arm pmap, one policy/audit block after the pmap
state it depends on, one Normal-NC-only guard after wimg_to_pte(), and two
call sites in pmap_map_bd_with_options() and pmap_enter_options_addr().

Every anchor is checked against the real source; a missing or duplicated
anchor fails closed. The pure decisions live in ios16/gpu/giulia_gpu_pmap.h and
ios16/gpu/giulia_gpu_fence_pmap.h, which the GPU service patch installs at
iokit/Kernel/arm/ together with this generator's output. This module does not
modify sources.
"""
from __future__ import annotations

import argparse
import difflib
from pathlib import Path
import subprocess
import tempfile


PATHS = ('osfmk/arm/pmap/pmap.c',)
# Static 0086 provenance: Apple XNU 1b191cb58250d0705d8a51287127505aa4bc0789,
# applied after the Sweet platform patches and 0081 (high physical cache sync).
XNU_COMMIT = '1b191cb58250d0705d8a51287127505aa4bc0789'
REFERENCE_COMMIT = 'd68e05df683f863f054b0f9c063c54d2b1342b2a'

INCLUDE_ANCHOR = '#include <arm/pmap/pmap_internal.h>\n'
STATE_ANCHOR = 'SECURITY_READ_ONLY_LATE(pmap_paddr_t)   vm_last_phys = (pmap_paddr_t) 0;\n'
BOOT_ANCHOR = '\tpmap_lock_init(kernel_pmap);\n'
RETIRE_ANCHOR = '\tpmap_initialized = TRUE;\n'
BD_ANCHOR = '\t    mem_attr | ARM_PTE_TYPE | ARM_PTE_NX | ARM_PTE_PNX | ARM_PTE_AF;\n'
ENTER_ANCHOR = ('\tkern_return_t kr = KERN_FAILURE;\n\n\n'
                '\tPMAP_TRACE(2, PMAP_CODE(PMAP__ENTER) | DBG_FUNC_START,\n')
WIMG_TO_PTE_ANCHOR = '''	return pte;
}


/*
 * Construct a PTE (and the physical page attributes) for the given virtual to
 * physical mapping.'''

_INCLUDES = '''#include "../../../iokit/Kernel/arm/giulia_gpu_fence_pmap.h"
#include "../../../iokit/Kernel/arm/giulia_gpu_pmap.h"
'''

_STATE = r'''
#if defined(ARM64_BOARD_CONFIG_SWEET)
/* Native GPU fence CPU gate. Generated by scripts/ios16_gpu_pmap_patch.py.
 * Source baseline: XNU 1b191cb58250d0705d8a51287127505aa4bc0789 with the
 * Sweet platform patches. Static state is retained until reboot; there is no
 * reset, release or de-quarantine path. Decisions are made by the pure policy
 * headers installed by the GPU service patch, never here.
 */
extern unsigned long gPhysBase, gPhysSize;

static struct {
	unsigned boot_valid, retired, blocked;
	uint64_t boot_tcr, boot_mair, boot_page;
} giulia_gpu_pmap_state;

static uint64_t
giulia_gpu_pmap_read_mair(void)
{
	return (uint64_t)__builtin_arm_rsr64("MAIR_EL1");
}
static uint64_t
giulia_gpu_pmap_read_tcr(void)
{
	return (uint64_t)__builtin_arm_rsr64("TCR_EL1");
}
static uint64_t
giulia_gpu_pmap_read_ttbr1(void)
{
	/* BADDR only: bits 63:48 carry TTBR1's ASID and are not translated. */
	return (uint64_t)__builtin_arm_rsr64("TTBR1_EL1") & 0x0000ffffffffffffULL;
}

static int
giulia_gpu_pmap_policy(struct ggpm_policy *out)
{
	struct ggpm_policy p = { 0 };

	if (!out) {
		return 0;
	}
	p.abi = GGPM_ABI;
	p.boot_valid = __atomic_load_n(&giulia_gpu_pmap_state.boot_valid, __ATOMIC_ACQUIRE) ? 1 : 0;
	p.page_bytes = pt_attr_page_size(pmap_get_pt_attr(kernel_pmap));
	p.mair = giulia_gpu_pmap_read_mair();
	p.tcr = giulia_gpu_pmap_read_tcr();
	p.ttbr1 = giulia_gpu_pmap_read_ttbr1();
	p.physmap_base = (uint64_t)gPhysBase;
	p.physmap_bytes = (uint64_t)gPhysSize;
	p.managed_base = (uint64_t)vm_first_phys;
	p.managed_bytes = (uint64_t)(vm_last_phys - vm_first_phys);
	*out = p;
	return 1;
}

/* Bootstrap-only: latch what the MMU actually reports before any driver can
 * map memory, and refuse to continue with a granule/attribute combination the
 * policy cannot describe. */
void
giulia_gpu_fence_cpu_boot_validate(uint64_t tcr, uint64_t mair, uint64_t page)
{
	unsigned valid = (ggfpm_page_valid(page) && ggfpm_tg1_page(tcr) == page &&
	    ggfpm_nc_mair(mair)) ? 1u : 0u;

	giulia_gpu_pmap_state.boot_tcr = tcr;
	giulia_gpu_pmap_state.boot_mair = mair;
	giulia_gpu_pmap_state.boot_page = page;
	__atomic_store_n(&giulia_gpu_pmap_state.boot_valid, valid, __ATOMIC_RELEASE);
}

/* The bootstrap device-mapping paths cannot fail, so a write-combining or
 * otherwise cacheable boot alias of the carveout latches a permanent refusal
 * instead of being audited later. */
void
giulia_gpu_fence_cpu_boot_map_check(uint64_t pa, uint64_t bytes, unsigned page)
{
	(void)page;
	if (ggpm_carveout_hit(pa, (size_t)bytes)) {
		__atomic_store_n(&giulia_gpu_pmap_state.blocked, 1u, __ATOMIC_RELEASE);
	}
}

void
giulia_gpu_fence_cpu_boot_retired(void)
{
	unsigned ok = (__atomic_load_n(&giulia_gpu_pmap_state.boot_valid, __ATOMIC_ACQUIRE) &&
	    !__atomic_load_n(&giulia_gpu_pmap_state.blocked, __ATOMIC_ACQUIRE)) ? 1u : 0u;

	__atomic_store_n(&giulia_gpu_pmap_state.retired, ok, __ATOMIC_RELEASE);
}

int
giulia_gpu_fence_cpu_policy_ready(void)
{
	struct ggpm_policy p;

	if (!__atomic_load_n(&giulia_gpu_pmap_state.retired, __ATOMIC_ACQUIRE) ||
	    __atomic_load_n(&giulia_gpu_pmap_state.blocked, __ATOMIC_ACQUIRE) ||
	    pmap_get_pt_attr(kernel_pmap) != native_pt_attr ||
	    !giulia_gpu_pmap_policy(&p) || !ggpm_policy_valid(&p) ||
	    p.ttbr1 != ((uint64_t)kernel_pmap->tte & 0x0000ffffffffffffULL)) {
		return 0;
	}
	return 1;
}

/* Audit one already-mapped CPU envelope. Every leaf is read under the kernel
 * pmap lock and judged by the same predicate; only the first and last
 * descriptors are handed to the pure seal, together with the exact count
 * derived from the requested span. No mapping, TLB or cache operation is
 * performed here. */
int
giulia_gpu_fence_cpu_audit(uintptr_t va, uint64_t pa, size_t bytes,
    unsigned writable, struct ggfpm_audit *out)
{
	struct ggfpm_audit audit;
	struct ggpm_policy p;
	uint64_t first = 0, last = 0;
	size_t count, i;

	if (!out || !giulia_gpu_fence_cpu_policy_ready() ||
	    !giulia_gpu_pmap_policy(&p) ||
	    !ggpm_alias_free(&p, pa, bytes) ||
	    !ggfpm_audit_range(va, pa, bytes, (unsigned)p.page_bytes, writable)) {
		return 0;
	}
	count = bytes / (size_t)p.page_bytes;
	pmap_lock(kernel_pmap, PMAP_LOCK_SHARED);
	for (i = 0; i < count; i++) {
		pt_entry_t *ptep = pmap_pte(kernel_pmap,
		    (vm_map_address_t)(va + i * p.page_bytes));
		uint64_t pte;

		if (ptep == PT_ENTRY_NULL) {
			first = 0;
			break;
		}
		pte = (uint64_t)*(volatile pt_entry_t *)ptep;
		if (!ggfpm_leaf_valid(pte, pa + i * p.page_bytes,
		    (unsigned)p.page_bytes, writable, p.mair)) {
			first = 0;
			break;
		}
		if (!first) {
			first = pte;
		}
		last = pte;
	}
	pmap_unlock(kernel_pmap, PMAP_LOCK_SHARED);
	if (!first || !giulia_gpu_fence_cpu_policy_ready() ||
	    !giulia_gpu_pmap_policy(&p) ||
	    !ggpm_audit_seal(&p, va, pa, bytes, writable, first, last, &audit)) {
		return 0;
	}
	*out = audit;
	return 1;
}
#endif
'''

_GUARD = r'''
/* Fixed-carveout cache policy: only attr index 1 (Normal NC, MAIR 0x44) may
 * ever alias this device range. A writeback or write-combining alias is
 * refused before a leaf is committed, which is what makes the policy's "no
 * writeback alias" claim enforceable rather than observational. */
static int
giulia_gpu_pmap_guard_enter(pmap_paddr_t pa, unsigned int flags)
{
	unsigned int wimg;
	pt_entry_t probe;

	if (!ggpm_carveout_hit((uint64_t)pa, PAGE_SIZE)) {
		return 0;
	}
	wimg = (flags & VM_WIMG_MASK) ? (flags & VM_WIMG_MASK) : VM_WIMG_DEFAULT;
	probe = wimg_to_pte(wimg, pa);
	return (unsigned int)(((uint64_t)probe >> 2) & 7u) != GGFPM_NC_INDEX;
}
'''


def _replace(text: str, old: str, new: str, name: str) -> str:
    if text.count(old) != 1:
        raise ValueError(f'GPU pmap source drift in {name}: expected one anchor, got {text.count(old)}')
    return text.replace(old, new)


def pmap_sources(source_texts: dict[str, str]) -> dict[str, str]:
    """Return changed source text; refuse an unpatched/different pmap."""
    for name in PATHS:
        if name not in source_texts:
            raise ValueError(f'Missing actual XNU source: {name}')
        if 'giulia_gpu_pmap_' in source_texts[name] or 'giulia_gpu_fence_cpu_' in source_texts[name]:
            raise ValueError(f'GPU pmap gate already present: {name}')
    name = PATHS[0]
    text = source_texts[name]
    text = _replace(text, INCLUDE_ANCHOR, INCLUDE_ANCHOR + _INCLUDES, name)
    text = _replace(text, STATE_ANCHOR, STATE_ANCHOR + _STATE, name)
    text = _replace(text, BOOT_ANCHOR, BOOT_ANCHOR +
        '#if defined(ARM64_BOARD_CONFIG_SWEET)\n'
        '\tgiulia_gpu_fence_cpu_boot_validate(__builtin_arm_rsr64("TCR_EL1"),\n'
        '\t    __builtin_arm_rsr64("MAIR_EL1"),\n'
        '\t    pt_attr_page_size(native_pt_attr));\n'
        '#endif\n', name)
    text = _replace(text, BD_ANCHOR, BD_ANCHOR +
        '#if defined(ARM64_BOARD_CONFIG_SWEET)\n'
        '\tif (__improbable((options & PMAP_MAP_BD_MASK) != 0)) {\n'
        '\t\tgiulia_gpu_fence_cpu_boot_map_check(start, end - start, PAGE_SIZE);\n'
        '\t}\n'
        '#endif\n', name)
    text = _replace(text, WIMG_TO_PTE_ANCHOR, '''	return pte;
}


#if defined(ARM64_BOARD_CONFIG_SWEET)
''' + _GUARD.strip('\n') + '''
#endif


/*
 * Construct a PTE (and the physical page attributes) for the given virtual to
 * physical mapping.''', name)
    text = _replace(text, ENTER_ANCHOR, '''	kern_return_t kr = KERN_FAILURE;

#if defined(ARM64_BOARD_CONFIG_SWEET)
	/* Fixed GPU carveout policy: refuse any non-Normal-NC alias before the
	 * PPL/internal path can commit a leaf. */
	if (__improbable(giulia_gpu_pmap_guard_enter(pa, flags))) {
		return KERN_PROTECTION_FAILURE;
	}
#endif

	PMAP_TRACE(2, PMAP_CODE(PMAP__ENTER) | DBG_FUNC_START,
''', name)
    text = _replace(text, RETIRE_ANCHOR, RETIRE_ANCHOR +
        '#if defined(ARM64_BOARD_CONFIG_SWEET)\n'
        '\tgiulia_gpu_fence_cpu_boot_retired();\n'
        '#endif\n', name)
    return {name: text}


def pmap_patch(source_texts: dict[str, str]) -> str:
    changed = pmap_sources(source_texts)
    return ''.join(''.join(difflib.unified_diff(source_texts[name].splitlines(True),
        changed[name].splitlines(True), fromfile='a/' + name, tofile='b/' + name))
        for name in PATHS)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, required=True,
                        help='Actual XNU tree (osfmk/arm/pmap/pmap.c) with the Sweet patches applied')
    parser.add_argument('--out', type=Path)
    parser.add_argument('--check-static', type=Path,
                        help='Require exact generator/static patch equality and git apply --check')
    args = parser.parse_args()
    if not args.out and not args.check_static:
        parser.error('Specify --out or --check-static')
    source_texts = {name: (args.source / name).read_text(encoding='utf-8') for name in PATHS}
    patch = pmap_patch(source_texts)
    if args.check_static:
        if args.check_static.read_text(encoding='utf-8') != patch:
            raise ValueError('Static GPU pmap patch differs from the actual-source generator')
        with tempfile.TemporaryDirectory(prefix='giulia-gpu-pmap-patch-') as directory:
            work = Path(directory)
            for name in PATHS:
                target = work / name
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(source_texts[name], encoding='utf-8', newline='\n')
            checked = work / 'pmap.patch'
            checked.write_text(patch, encoding='utf-8', newline='\n')
            subprocess.run(['git', '-c', 'core.autocrlf=false', 'apply', '--check', str(checked)],
                           cwd=work, check=True)
        print('GPU pmap static patch matches the actual-source generator and LF git apply --check')
    if args.out:
        args.out.write_text(patch, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
