"""Build the deterministic local A750 pack; only digests enter kernel source."""
import argparse
import hashlib
import json
from pathlib import Path
import struct
from ios16_gpu import ROOT, CHIP_ID, FIRMWARE


def build_pack(folder, pins):
    entries = {p['name']: p for p in pins['firmware']}
    output = bytearray(4096)
    output[:8] = b'GGFWPK1\0'
    struct.pack_into('<II', output, 8, CHIP_ID, 4)
    struct.pack_into('<I', output, 20, 1)
    for index, name in enumerate(FIRMWARE):
        data = (folder/name).read_bytes()
        entry = entries[name]
        digest = hashlib.sha256(data).digest()
        if len(data) != entry['size'] or digest.hex() != entry['sha256']:
            raise ValueError('Unqualified GPU firmware: ' + name)
        at = 64 + index*64
        struct.pack_into('<IIII', output, at, index, len(output), len(data), 0)
        output[at+16:at+48] = digest
        output.extend(data)
        output.extend(bytes((-len(output)) % 4096))
    struct.pack_into('<I', output, 16, len(output))
    return bytes(output)


def pin_header(pack):
    digest = hashlib.sha256(pack).digest()
    return ('/* SPDX-License-Identifier: BSD-2-Clause-Patent */\n'
            '/* Generated by make-gpu-firmware-pack.py; contains no firmware bytes. */\n'
            '#ifndef GIULIA_GPU_FIRMWARE_PIN_H\n#define GIULIA_GPU_FIRMWARE_PIN_H\n'
            f'#define GG_FIRMWARE_PACK_BYTES {len(pack)}u\n'
            'static const unsigned char gg_firmware_pack_sha256[32] = {\n    ' +
            ','.join(f'0x{x:02x}' for x in digest) + '\n};\n#endif\n')


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--firmware-dir', type=Path, required=True)
    p.add_argument('--out', type=Path, required=True)
    p.add_argument('--pin-header', type=Path, help='Write source digest header after explicit regeneration')
    a = p.parse_args()
    pack = build_pack(a.firmware_dir, json.loads((ROOT/'hardware/sm8650-gpu.json').read_text()))
    header = pin_header(pack)
    if a.pin_header:
        a.pin_header.write_text(header, encoding='utf-8', newline='\n')
    elif (ROOT/'ios16/gpu/giulia_gpu_firmware_pin.h').read_text() != header:
        raise ValueError('Pack differs from compiled kernel pin')
    if a.out.exists() and a.out.read_bytes() != pack:
        raise ValueError('Refusing to replace a different firmware pack')
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_bytes(pack)
    print(f'GPU pack: {len(pack)} bytes, SHA256 {hashlib.sha256(pack).hexdigest()}')


if __name__ == '__main__':
    main()
