"""Pinned Ace 5 audio resource descriptions; never accesses a device."""
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / 'hardware/sm8650-audio.json'
HEADER = ROOT / 'ios16/audio/giulia_audio_mapping.h'


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def load_mapping(path=MANIFEST):
    data = json.loads(Path(path).read_text(encoding='utf-8'))
    if data['schema'] != 1 or data['board'] != 'giulia' or data['soc'] != 'SM8650':
        raise ValueError('Expected the Ace 5 audio mapping')
    names = set()
    for item in data['regions']:
        name, base, size = item['id'], item['base'], item['bytes']
        if not re.fullmatch('[A-Z][A-Z0-9_]*', name) or name in names:
            raise ValueError('Invalid/duplicate resource ID')
        names.add(name)
        if not 0 < base < 2**64 or not 0 <= size < 2**64-base:
            raise ValueError('Invalid resource range')
        if item['kind'] not in ('mmio', 'reserved') or type(item['enabled']) is not bool:
            raise ValueError('Invalid resource classification')
    return data


def render_header(data):
    """Generate immutable tables. Helpers only resolve numbers, never map MMIO."""
    q = json.dumps
    lines = ['/* SPDX-License-Identifier: BSD-2-Clause-Patent',
             ' * Generated by scripts/check-audio-mapping.py --write-header.',
             ' * Source: hardware/sm8650-audio.json. No MMIO, allocation or DMA ownership.',
             ' * enabled means Android DT availability, not XNU hardware readiness.',
             ' */', '#ifndef GIULIA_AUDIO_MAPPING_H', '#define GIULIA_AUDIO_MAPPING_H',
             '#include <stdint.h>', '#include <stddef.h>', '',
             '#define GAMAP_DTS_SHA256 '+q(data['android_device_tree']['decoded_sha256']),
             '#define GAMAP_SOURCE_COMMIT '+q(data['source_commit']),
             'enum { GAMAP_MMIO, GAMAP_RESERVED };',
             'enum { '+', '.join('GAMAP_'+r['id'] for r in data['regions'])+', GAMAP_REGIONS };',
             'struct gamap_region {',
             '    const char *name; uint64_t physical; size_t bytes; unsigned kind,enabled;',
             '};', 'static const struct gamap_region gamap_regions[GAMAP_REGIONS] = {']
    for r in data['regions']:
        lines.append('    {%s,0x%xULL,0x%x,%s,%u},' %
                     (q(r['id']), r['base'], r['bytes'], 'GAMAP_'+r['kind'].upper(), r['enabled']))
    lines += ['};', '', 'struct gamap_irq { const char *name; unsigned spi,intid; };',
              'static const struct gamap_irq gamap_irqs[] = {']
    for irq in data['gic_interrupts']:
        lines.append('    {%s,%u,%u},' % (q(irq['name']), irq['spi'], irq['intid']))
    lines += ['};', '', 'struct gamap_bus_device {',
              '    const char *name,*bus; uint64_t address; unsigned reset_gpio,has_reset_gpio;',
              '};', 'static const struct gamap_bus_device gamap_devices[] = {']
    for d in data['bus_devices']:
        lines.append('    {%s,%s,0x%xULL,%u,%u},' % (q(d['name']), q(d['bus']), d['address'],
                     d.get('reset_gpio', 0), 'reset_gpio' in d))
    lines += ['};', '', '#define GAMAP_IOVA_BASE 0x%xULL' % data['audio_dma']['iova_base'],
              '#define GAMAP_IOVA_BYTES 0x%xULL' % data['audio_dma']['iova_bytes'],
              '#define GAMAP_GPR_DOMAIN %uu' % data['transport']['gpr_domain'],
              '#define GAMAP_GPR_CHANNEL '+q(data['transport']['gpr_channel']),
              '#define GAMAP_GLINK_PID %uu' % data['transport']['remote_pid'],
              '#define GAMAP_IPCC_CLIENT %uu' % data['transport']['ipcc_client'],
              '#define GAMAP_IPCC_SIGNAL %uu' % data['transport']['ipcc_signal'],
              '#define GAMAP_SPF_SERVICE %uu' % data['transport']['services']['spf_core'],
              '#define GAMAP_PACKET_SERVICE %uu' % data['transport']['services']['audio_packet'],
              '#define GAMAP_PRM_SERVICE %uu' % data['transport']['services']['prm'],
              'struct gamap_sid { unsigned id,mask; };',
              'static const struct gamap_sid gamap_sids[] = {']
    for sid in data['audio_dma']['streams']:
        lines.append('    {0x%x,0x%x},' % (sid['sid'], sid['mask']))
    lines += ['};', '', HELPERS, '#endif', '']
    return '\n'.join(lines)


HELPERS = '''/* Only enabled AP MMIO descriptors can be resolved. Reserved DSP RAM and
 * bus addresses are never accepted as host registers. No pointer is returned.
 * The caller must separately establish power, ownership and an OS mapping. */
static inline int gamap_resolve(unsigned id,size_t offset,unsigned width,uint64_t *physical)
{
    if(id>=GAMAP_REGIONS || !physical || (width!=1 && width!=2 && width!=4 && width!=8))return 0;
    const struct gamap_region *r=&gamap_regions[id];
    if(!r->enabled || r->kind!=GAMAP_MMIO || !r->bytes ||
       (r->physical&(width-1)) || (offset&(width-1)) ||
       width>r->bytes || offset>r->bytes-width ||
       r->bytes>(uint64_t)-1-r->physical)return 0;
    *physical=r->physical+offset;return 1;
}

/* Describe page coverage without touching a page table. Keep the original
 * resource bounds for access checks: padding is not a register aperture. */
static inline int gamap_page_window(unsigned id,size_t page,uint64_t *base,size_t *bytes,size_t *bias)
{
    uint64_t pa;
    if(!base || !bytes || !bias || (page!=4096 && page!=16384) ||
       !gamap_resolve(id,0,1,&pa))return 0;
    const struct gamap_region *r=&gamap_regions[id];
    size_t delta=(size_t)(pa&(page-1));
    if(r->bytes>(size_t)-1-delta || r->bytes+delta>(size_t)-1-(page-1))return 0;
    size_t span=(r->bytes+delta+page-1)&~(page-1);
    uint64_t start=pa-delta;
    if(span>(uint64_t)-1-start)return 0;
    *base=start;*bytes=span;*bias=delta;return 1;
}

/* Android's IOVA pool is evidence, not an allocated XNU DMA arena. */
static inline int gamap_iova_offset(uint64_t address,size_t bytes,size_t *offset)
{
    if(!offset || !bytes || address<GAMAP_IOVA_BASE || bytes>GAMAP_IOVA_BYTES ||
       address-GAMAP_IOVA_BASE>GAMAP_IOVA_BYTES-bytes)return 0;
    *offset=(size_t)(address-GAMAP_IOVA_BASE);return 1;
}'''


def verify_dts(data, path):
    raw = Path(path).read_bytes()
    if sha256(raw) != data['android_device_tree']['decoded_sha256']:
        raise ValueError('Captured Android DTS hash mismatch; requalify the board map')
    # Numeric dtc output only, using the existing qualified DTS reader.
    from ios16_gpu import block, cells, strings
    text = raw.decode('utf-8')
    for check in data['dt_checks']:
        node = block(text, check['node'])
        reader = strings if check['type'] == 'strings' else cells
        if reader(node, check['property']) != check['value']:
            raise ValueError('DTS mismatch: '+check['node']+'/'+check['property'])
    return len(data['dt_checks'])


def verify_files(root, records):
    root = Path(root).resolve()
    for item in records:
        path = (root / item['path']).resolve()
        if not path.is_relative_to(root):
            raise ValueError('Evidence path escapes root')
        content = path.read_bytes()
        if len(content) != item['bytes'] or sha256(content) != item['sha256']:
            raise ValueError('Evidence hash/size mismatch: '+item['path'])
    return len(records)
